#!/usr/bin/env python3
"""Compile the supplied pixel-art Rasta lion into a 4-bit FM-1 sprite.

Input : assets/lion/lion_source.webp (supplied by the user)
Output: src/ui/rr_lion_atlas.h  (palette RGB565 + packed 4bpp pixels, index 0 = transparent)
        build/lion_preview.png   (8x enlarged preview for inspection)

The art is drawn on a ~12 px grid. Each output pixel takes the most common
colour of the central part of its source cell, so pixel edges stay sharp.
Requires Pillow. Ordinary firmware builds use the checked-in header.
"""
import collections, os, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'lion', 'lion_source.webp')
OUT = os.path.join(ROOT, 'src', 'ui', 'rr_lion_atlas.h')
PREVIEW = os.path.join(ROOT, 'build', 'lion_preview.png')
MAX = 100
COLOURS = 15  # plus transparent


def main():
    im = Image.open(SRC).convert('RGB')
    w, h = im.size
    px = im.load()
    dark = lambda c: sum(c) < 700
    xs = [x for x in range(w) for y in range(0, h, 3) if dark(px[x, y])]
    ys = [y for y in range(h) for x in range(0, w, 3) if dark(px[x, y])]
    x0, x1, y0, y1 = min(xs), max(xs) + 1, min(ys), max(ys) + 1
    cell = max(x1 - x0, y1 - y0) / MAX
    ow, oh = round((x1 - x0) / cell), round((y1 - y0) / cell)
    cells = []
    for oy in range(oh):
        for ox in range(ow):
            cx0, cy0 = x0 + ox * cell, y0 + oy * cell
            votes = collections.Counter()
            for sy in range(3):
                for sx in range(3):
                    c = px[min(w - 1, int(cx0 + cell * (0.3 + 0.2 * sx))), min(h - 1, int(cy0 + cell * (0.3 + 0.2 * sy)))]
                    votes[tuple(v >> 3 << 3 for v in c)] += 1
            c = votes.most_common(1)[0][0]
            cells.append(None if min(c) >= 232 else c)
    # Curated palette sampled from the supplied artwork (nearest-colour mapping
    # keeps the cream muzzle, pink tongue and mane shades that median cut loses).
    rgb = [(0, 0, 0), (8, 4, 4), (248, 180, 36), (248, 196, 24), (252, 216, 80),
           (244, 160, 20), (150, 76, 18), (98, 38, 18), (64, 24, 12), (246, 226, 168),
           (214, 8, 16), (0, 132, 44), (232, 100, 120), (255, 255, 255), (180, 120, 40), (120, 56, 20)]
    def nearest(c):
        return min(range(1, len(rgb)), key=lambda i: sum((a - b) ** 2 for a, b in zip(c, rgb[i])))
    out = [0 if c is None else nearest(c) for c in cells]
    used = sorted(set(out) - {0})
    rgb565 = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in rgb]
    packed = []
    for y in range(oh):
        row = out[y * ow:(y + 1) * ow] + [0] * (ow & 1)
        packed += [row[i] | (row[i + 1] << 4) for i in range(0, len(row), 2)]
    stride = (ow + 1) // 2
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', newline='\n') as f:
        f.write('/* Generated by tools/lion_assets.py from assets/lion/lion_source.webp. Do not edit. */\n')
        f.write('/* Supplied artwork; see assets/lion/README.md for provenance. */\n')
        f.write(f'#define RR_LION_W {ow}\n#define RR_LION_H {oh}\n#define RR_LION_STRIDE {stride}\n')
        f.write('static const uint16_t rr_lion_palette[16] = {' + ','.join(f'0x{v:04x}' for v in rgb565 + [0] * (16 - len(rgb565))) + '};\n')
        # Run-length coded: one byte per run, (length-1) << 4 | colour, length 1..16.
        runs = []
        i = 0
        while i < len(out):
            n = 1
            while i + n < len(out) and out[i + n] == out[i] and n < 16:
                n += 1
            runs.append(((n - 1) << 4) | out[i])
            i += n
        f.write(f'#define RR_LION_RLE {len(runs)}\n')
        f.write('static const uint8_t rr_lion_rle[RR_LION_RLE] = {\n')
        for k in range(0, len(runs), 32):
            f.write(''.join(f'{b},' for b in runs[k:k + 32]) + '\n')
        f.write('};\n')
    os.makedirs(os.path.dirname(PREVIEW), exist_ok=True)
    prev = Image.new('RGB', (ow, oh))
    prev.putdata([rgb[i] if i else (40, 40, 40) for i in out])
    prev.resize((ow * 8, oh * 8), Image.NEAREST).save(PREVIEW)
    print(f'lion {ow}x{oh}, {len(used)} colours, {len(packed)} bytes unpacked')
    for i, c in enumerate(rgb):
        print(i, c)


if __name__ == '__main__':
    main()
